#!/usr/bin/env python3
"""
Project Chimera: Act V / Phase L3 - Linux Quad-Compiler Triad Benchmark

Replicates the Phase 8 comparative benchmark on Linux x86_64, adding GCC as a
fourth compiler:

  | Compiler        | Rule 110 evaluation model                |
  | GCC 11.4        | C++20 NTTP template metaprogramming      |
  | Clang 14        | C++20 NTTP template metaprogramming      |
  | rustc 1.97.1    | Chalk-style Horn-clause trait resolution |
  | tsc 7.0.2       | Structural conditional-type reduction    |

Steps sweep: 10 / 50 / 100 / 500 / 1000 (defaults) + 5000 / 10000 (raised
limits). Peak RSS and wall time captured via /usr/bin/time -v.

Output: data/phaseL3_linux_quad_results.json
"""
import json
import re
import subprocess
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data"
TMP = REPO_ROOT / "linux" / "probes"

CPP_TEMPLATE = """#include "cpp_chimera/rule110.hpp"
using namespace chimera;
using InitialTape = Tape<0, 1, 1, 0, 1, 1, 1, 0>;
using FinalTape = Evolve_t<InitialTape, %d>;
int main() { return 0; }
"""

# Rust: type-level Peano counter generated by nested Succ wrappers.
RUST_TEMPLATE = """#![recursion_limit = "%d"]
use rust_chimera::*;
type Tape8 = Cons<Zero, Cons<One, Cons<One, Cons<Zero, Cons<One, Cons<One, Cons<One, Cons<Zero, Nil>>>>>>>>;
type Steps = %s;
type Out = <Tape8 as Evolve<Steps>>::Output;
pub fn f() { let _ = assert_type_eq::<Out, Out>; }
"""

TS_TEMPLATE = """import { EvolveTCO } from "../../src/type_engine/rule110";
type Tape8 = [0, 1, 1, 0, 1, 1, 1, 0];
type Out = EvolveTCO<Tape8, %d>;
export type { Out };
"""


def peano(n: int) -> str:
    return "PeanoSucc<" * n + "PeanoZero" + ">" * n


def rust_steps_expr(n: int) -> str:
    """Compose nested N-blocks: N4 = 10^4 nestings like the MRE trick, but here
    we just need literal Peano depth — generate a balanced alias tree."""
    # Direct nesting is fine — rustc parses N<...> deeply without issue.
    return peano(n)


def time_cmd(cmd):
    """Run cmd under /usr/bin/time -v; return (wall_ms, rss_mb, rc, stderr)."""
    t0 = time.time()
    proc = subprocess.run(["/usr/bin/time", "-v"] + cmd,
                          capture_output=True, text=True)
    wall_ms = (time.time() - t0) * 1000
    stderr = proc.stderr or ""
    rss = re.search(r"Maximum resident set size \(kbytes\): (\d+)", stderr)
    rss_mb = int(rss.group(1)) / 1024 if rss else None
    return wall_ms, rss_mb, proc.returncode, stderr


def bench_cpp(compiler, steps, depth_flag, extra_flags):
    src = TMP / f"bench_{compiler}_{steps}.cpp"
    src.write_text(CPP_TEMPLATE % steps)
    cmd = [compiler, "-std=c++20", "-fsyntax-only", f"-I{REPO_ROOT}"] + extra_flags + [str(src)]
    if depth_flag:
        cmd.insert(-1, depth_flag)
    w, rss, rc, err = time_cmd(cmd)
    src.unlink()
    return {"wall_ms": round(w, 1), "rss_mb": rss, "rc": rc,
            "depth_exceeded": "maximum depth" in err or "recursively required" in err}


def bench_rust(steps, limit):
    src = TMP / f"bench_rust_{steps}.rs"
    src.write_text(RUST_TEMPLATE % (limit, rust_steps_expr(steps)))
    out_dir = TMP / ".rust_out"
    out_dir.mkdir(exist_ok=True)
    w, rss, rc, err = time_cmd([
        "rustc", "--crate-type=lib", "--edition=2021",
        "-L", str(REPO_ROOT / "rust_chimera" / "target" / "release" / "deps"),
        "--extern", "rust_chimera=" + str(
            REPO_ROOT / "rust_chimera" / "target" / "release" / "librust_chimera.rlib"),
        str(src), "--emit", f"metadata={out_dir}/{src.stem}.rmeta",
    ])
    src.unlink()
    (out_dir / f"{src.stem}.rmeta").unlink(missing_ok=True)
    return {"wall_ms": round(w, 1), "rss_mb": rss, "rc": rc,
            "depth_exceeded": "E0275" in err or "overflow" in err}


def bench_ts(steps):
    src = TMP / f"bench_ts_{steps}.ts"
    src.write_text(TS_TEMPLATE % steps)
    w, rss, rc, err = time_cmd([
        "npx", "tsc", "--noEmit", "--ignoreConfig", "--strict", str(src)])
    src.unlink()
    return {"wall_ms": round(w, 1), "rss_mb": rss, "rc": rc,
            "depth_exceeded": "TS2589" in err}


def main():
    # Ensure the rust lib is built
    subprocess.run(["cargo", "build", "--release", "--manifest-path",
                    "rust_chimera/Cargo.toml"], cwd=REPO_ROOT,
                   capture_output=True)

    results = {"metadata": {
        "platform": "linux-x86_64",
        "gcc": "11.4.0", "clang": "14.0.0", "rustc": "1.97.1",
        "typescript": "7.0.2-native",
    }, "runs": []}

    steps_list = [10, 50, 100, 500, 1000]
    print(f"{'steps':>6} {'compiler':<10} {'wall_ms':>10} {'rss_MB':>8} {'rc':>3} {'depth_exceeded'}")
    for s in steps_list:
        for comp, fn in [
            ("g++",     lambda: bench_cpp("g++", s, None, [])),
            ("clang++", lambda: bench_cpp("clang++", s, None, [])),
            ("rustc",   lambda: bench_rust(s, max(1024, s * 4))),
            ("tsc",     lambda: bench_ts(s)),
        ]:
            r = fn()
            r["compiler"], r["steps"] = comp, s
            results["runs"].append(r)
            print(f"{s:>6} {comp:<10} {r['wall_ms']:>10.0f} "
                  f"{(r['rss_mb'] or 0):>8.0f} {r['rc']:>3} {r['depth_exceeded']}",
                  flush=True)

    # Extended horizon: raised limits
    for s, comp, fn in [
        (5000, "g++",     lambda: bench_cpp("g++", 5000, "-ftemplate-depth=20000", [])),
        (10000, "g++",    lambda: bench_cpp("g++", 10000, "-ftemplate-depth=40000", [])),
        (5000, "clang++", lambda: bench_cpp("clang++", 5000, "-ftemplate-depth=20000", [])),
        (10000, "clang++",lambda: bench_cpp("clang++", 10000, "-ftemplate-depth=40000", [])),
        (5000, "rustc",   lambda: bench_rust(5000, 60000)),
        (10000, "rustc",  lambda: bench_rust(10000, 120000)),
    ]:
        r = fn()
        r["compiler"], r["steps"] = comp, s
        results["runs"].append(r)
        print(f"{s:>6} {comp:<10} {r['wall_ms']:>10.0f} "
              f"{(r['rss_mb'] or 0):>8.0f} {r['rc']:>3} {r['depth_exceeded']}",
              flush=True)

    out = DATA_DIR / "phaseL3_linux_quad_results.json"
    out.write_text(json.dumps(results, indent=2))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
